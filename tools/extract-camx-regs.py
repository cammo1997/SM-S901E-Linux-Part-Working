#!/usr/bin/env python3
"""Extract CamX sensormodule .bin register sequences into mainline Linux v4l2-cci C headers."""

import argparse
from pathlib import Path
import struct

BIN_DIR = Path("/mnt/c/s22/camx-bins")


def load_recs(path: Path):
    data = path.read_bytes()
    n_secs = struct.unpack_from("<I", data, 0xA4)[0]
    secs = {}
    for i in range(n_secs):
        sid, off, size = struct.unpack_from("<3I", data, 0xA8 + 12 * i)
        secs[sid] = (off, size)
    off0, size0 = secs[0]
    data_off = secs[1][0]
    recs = []
    for p in range(off0, off0 + size0 - 55, 56):
        rid, name, kind, a, b, doff, dsz = struct.unpack_from("<I32s5I", data, p)
        name = name.split(b"\0")[0].decode("ascii", "replace")
        recs.append((rid, name, kind, a, b, doff, dsz, data[data_off + doff : data_off + doff + dsz]))
    return recs


def expand_reg_setting(raw: bytes, dsz: int, byid: dict):
    out = []
    for i in range(0, dsz - 39, 40):
        w = struct.unpack_from("<10I", raw, i)
        addr = w[2]
        cnt = w[3]
        data_rec = byid.get(w[4])
        data_type = w[5]  # 1 = byte, 2 = word
        op = w[7]         # 0 = random write, 1 = continuous/seq, 6 = burst
        delay_rec = byid.get(w[9])
        dly = struct.unpack_from("<I", delay_rec[7])[0] if delay_rec and delay_rec[6] >= 4 else 0

        if not data_rec or data_rec[6] < 4 * max(cnt, 1):
            raise ValueError(f"Unexpected registerData size {data_rec[6] if data_rec else None} for cnt={cnt} at addr={addr:#x}")

        vals = [struct.unpack_from("<I", data_rec[7], j * 4)[0] for j in range(cnt)]
        for j, val in enumerate(vals):
            # Samsung 0x6f12 T&M port writes always target 0x6f12 even during burst (op==6)
            reg_addr = addr if (addr == 0x6F12 or op in (0, 6)) else addr + j * data_type
            out.append((reg_addr, val, dly if j == len(vals) - 1 else 0, data_type))
    return out


def parse_bin(path: Path):
    recs = load_recs(path)
    byid = {r[0]: r for r in recs}
    mode_names = [
        recs[i + 1][7].split(b"\0")[0].decode("ascii", "replace")
        for i, r in enumerate(recs)
        if r[1] == "modeName" and i + 1 < len(recs)
    ]

    init_regs = []
    master_regs = []
    mode_regs = []
    ctx = ""
    for rid, name, kind, a, b, doff, dsz, raw in recs:
        if name == "regSetting":
            entries = expand_reg_setting(raw, dsz, byid)
            if ctx == "initSettings":
                init_regs = entries
            elif ctx == "masterSettings":
                master_regs = entries
            elif ctx == "integrationInfo":
                mode_regs.append(entries)
        elif name not in ("slaveAddr", "registerData", "delayUs", "regSetting"):
            ctx = name

    if len(mode_names) != len(mode_regs):
        raise RuntimeError(f"{path.name}: mode_names ({len(mode_names)}) != mode_regs ({len(mode_regs)})")

    return {
        "init": init_regs,
        "master": master_regs,
        "modes": list(zip(mode_names, mode_regs)),
    }


def format_cci_array(name: str, comment: str, regs, width_bits: int, with_delay: bool, struct_type: str):
    reg_macro = "CCI_REG8" if width_bits == 8 else "CCI_REG16"
    val_fmt = "0x{:02x}" if width_bits == 8 else "0x{:04x}"
    lines = [f"/* {comment} ({len(regs)} writes) */"]
    if with_delay:
        lines.append(f"static const struct {struct_type} {name}[] = {{")
        for addr, val, dly, dtype in regs:
            lines.append(f"\t{{ {reg_macro}({addr:#06x}), {val_fmt.format(val)}, {dly} }},")
    else:
        lines.append(f"static const struct cci_reg_sequence {name}[] = {{")
        for addr, val, dly, dtype in regs:
            if dly:
                raise AssertionError(f"Non-zero delay {dly} in zero-delay table {name} at {addr:#x}")
            lines.append(f"\t{{ {reg_macro}({addr:#06x}), {val_fmt.format(val)} }},")
    lines.append("};\n")
    return "\n".join(lines)


def emit_header(out_paths, guard: str, extra_struct: str, blocks: list[str]):
    content = [
        "/* SPDX-License-Identifier: GPL-2.0-only */",
        "/* Auto-generated by tools/extract-camx-regs.py from Samsung S22 (r0q) CamX sensormodule binaries. */",
        f"#ifndef {guard}",
        f"#define {guard}",
        "",
        "#include <media/v4l2-cci.h>",
        "",
    ]
    if extra_struct:
        content.append(extra_struct)
        content.append("")
    content.extend(blocks)
    content.append(f"#endif /* {guard} */")
    text = "\n".join(content) + "\n"
    for p in out_paths:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
        print(f"Wrote {p} ({len(text)} bytes)")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--bin-dir", type=Path, default=BIN_DIR)
    parser.add_argument("--kernel-dir", type=Path, default=Path("/home/netobr/s22-kernel/linux-7.2.11"))
    parser.add_argument("--repo-dir", type=Path, default=Path("/home/netobr/s22-linux"))
    args = parser.parse_args()

    i2c_dir = args.kernel_dir / "drivers/media/i2c"
    repo_k = args.repo_dir / "kernel"

    imx374_crop = parse_bin(args.bin_dir / "com.samsung.sensormodule.1_sony_imx374.bin")
    imx374_full = parse_bin(args.bin_dir / "com.samsung.sensormodule.12_sony_imx374_full.bin")
    s5k3k1 = parse_bin(args.bin_dir / "com.samsung.sensormodule.3_lsi_s5k3k1.bin")
    imx563 = parse_bin(args.bin_dir / "com.samsung.sensormodule.2_sony_imx563.bin")
    s5kgn3 = parse_bin(args.bin_dir / "com.samsung.sensormodule.0_lsi_s5kgn3.bin")

    # 1. IMX374
    emit_header(
        [i2c_dir / "imx374-regs.h", repo_k / "imx374-regs.h"],
        "__IMX374_REGS_H__",
        "",
        [
            format_cci_array("imx374_init_regs", "initSettings (1_sony_imx374.bin)", imx374_crop["init"], 8, False, ""),
            format_cci_array(
                "imx374_mode_1616x912_30fps_regs",
                f"Mode 5: {imx374_crop['modes'][5][0]}",
                imx374_crop["modes"][5][1],
                8,
                False,
                "",
            ),
            format_cci_array(
                "imx374_mode_3648x2736_30fps_regs",
                f"Full Mode 0: {imx374_full['modes'][0][0]}",
                imx374_full["modes"][0][1],
                8,
                False,
                "",
            ),
        ],
    )

    # 2. S5K3K1
    emit_header(
        [i2c_dir / "s5k3k1-regs.h", repo_k / "s5k3k1-regs.h"],
        "__S5K3K1_REGS_H__",
        "struct s5k3k1_reg_seq {\n\tu32 reg;\n\tu16 val;\n\tu16 delay_us;\n};",
        [
            format_cci_array("s5k3k1_init_regs", "initSettings (3_lsi_s5k3k1.bin)", s5k3k1["init"], 16, True, "s5k3k1_reg_seq"),
            format_cci_array("s5k3k1_master_regs", "masterSettings (3_lsi_s5k3k1.bin)", s5k3k1["master"], 16, False, ""),
            format_cci_array(
                "s5k3k1_mode_3648x2736_30fps_regs",
                f"Mode 0: {s5k3k1['modes'][0][0]}",
                s5k3k1["modes"][0][1],
                16,
                False,
                "",
            ),
            format_cci_array(
                "s5k3k1_mode_1824x1368_30fps_regs",
                f"Mode 5: {s5k3k1['modes'][5][0]}",
                s5k3k1["modes"][5][1],
                16,
                False,
                "",
            ),
        ],
    )

    # 3. IMX563
    emit_header(
        [i2c_dir / "imx563-regs.h", repo_k / "imx563-regs.h"],
        "__IMX563_REGS_H__",
        "",
        [
            format_cci_array("imx563_init_regs", "initSettings (2_sony_imx563.bin)", imx563["init"], 8, False, ""),
            format_cci_array("imx563_master_regs", "masterSettings (2_sony_imx563.bin)", imx563["master"], 8, False, ""),
            format_cci_array(
                "imx563_mode_4032x3024_30fps_regs",
                f"Mode 0: {imx563['modes'][0][0]}",
                imx563["modes"][0][1],
                8,
                False,
                "",
            ),
            format_cci_array(
                "imx563_mode_2016x1512_30fps_regs",
                f"Mode 6: {imx563['modes'][6][0]}",
                imx563["modes"][6][1],
                8,
                False,
                "",
            ),
        ],
    )

    # 4. S5KGN3
    emit_header(
        [i2c_dir / "s5kgn3-regs.h", repo_k / "s5kgn3-regs.h"],
        "__S5KGN3_REGS_H__",
        "struct s5kgn3_reg_seq {\n\tu32 reg;\n\tu16 val;\n\tu16 delay_us;\n};",
        [
            format_cci_array("s5kgn3_init_regs", "initSettings (0_lsi_s5kgn3.bin)", s5kgn3["init"], 16, True, "s5kgn3_reg_seq"),
            format_cci_array(
                "s5kgn3_mode_4080x3060_30fps_regs",
                f"Mode 2: {s5kgn3['modes'][2][0]}",
                s5kgn3["modes"][2][1],
                16,
                False,
                "",
            ),
            format_cci_array(
                "s5kgn3_mode_2040x1532_30fps_regs",
                f"Mode 26: {s5kgn3['modes'][26][0]}",
                s5kgn3["modes"][26][1],
                16,
                False,
                "",
            ),
        ],
    )


if __name__ == "__main__":
    main()
